// German (Germany). The German line is the lesson.
// script is a sound-it-out guide. Capitals mark the stressed syllable.
// kh is the ch sound. ü and ö stay as they are; the sounds lesson explains them.

function g(id, en, de, guide, hint) {
  const spoken = de.replace(/[¿¡?!…]/g, "").replace(/\s+/g, " ").trim();
  return p(id, en, de, guide, hint, spoken);
}

